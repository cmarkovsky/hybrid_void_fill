#!/usr/bin/env python3
'Read-only verifier for the manuscript evaluation subset (excluding RGI60-14.17287).'
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from decimal import ROUND_HALF_EVEN, Decimal
from pathlib import Path

import numpy as np
import pandas as pd

from common import Paths, Selection, sha256

FROZEN = {"model": "f87e0f8779d2eb9f4775ffa661c29267ac6f7efef7d30d51e1b7d3d0ef75505e",
          "cache": "a4f6be88c96c5f30fa0f1a04e94b764a271f602b2b9fe5949d64d87a9b66a3d3",
          "residuals": "79b8117a8d8198312c0f984944a7a40b2c0673dbd4231fc2ba7573f833f2942c",
          "release_zip": "146208bb85b37adb07b8ade832acb63f7d9ead1ade0902c6a2098d037dc5fd2a"}
RES = "results/manuscript"


def sig3(v):
    d = Decimal(str(float(v)))
    q = d.quantize(Decimal(1).scaleb(d.copy_abs().adjusted() - 2), rounding=ROUND_HALF_EVEN)
    return float(q)


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-root", type=Path, required=True)
    ap.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    ap.add_argument("--out", type=Path, required=True)
    
    ap.add_argument("--stage-tree", type=Path, help="Results tree generated by run_production_stages.py")
    ap.add_argument("--figures", type=Path, help="Generated figure directory; defaults to committed figures")
    a = ap.parse_args()
    repo = a.repo.resolve()
    paths, sel = Paths(a.data_root, repo), Selection(repo)
    figures = a.figures.resolve() if a.figures else repo / "figures"
    X = sel.excluded
    sub = a.stage_tree.resolve() if a.stage_tree else paths.root / "derived/manuscript"
    R = {}

    def check(name, ok, **info):
        R[name] = dict(passed=bool(ok), **info)
        print(("PASS " if ok else "FAIL ") + name, flush=True)

    # 1 frozen identities
    rel = paths["frozen_release"]
    got = {"model": sha256(rel / "model/model.json"), "cache": sha256(paths["reference_predictions"]), "residuals": sha256(paths["reference_residuals"]),
           "release_zip": sha256(rel.with_suffix(".zip")) if rel.with_suffix(".zip").exists() else None}
    check("1_frozen_identities", got == FROZEN, observed=got)
    check("1b_repo_model_matches_frozen", sha256(repo / "models/hybrid/model.json") == FROZEN["model"])

    # 2 membership
    mem = pd.read_csv(repo / "data/metadata/evaluation_membership.csv")
    e = mem[mem.evaluated]
    counts = {"test_glaciers": {**e.groupby("region").size().to_dict(), "all": len(e)}, "glacier_realizations": int(e.n_realizations.sum()),
              "targets_per_method": {**e.groupby("region").targets_per_method.sum().astype(int).to_dict(), "all": int(e.targets_per_method.sum())}}
    split = json.loads((repo / "data/metadata/splits/training_split.json").read_text())
    groups = pd.Series(split).value_counts().to_dict()
    check("2_membership_counts", counts == sel.expected, observed=counts)
    check("2b_production_split_unchanged", groups == {"train": 8179, "val": 1751, "test": 1755}
          and sha256(repo / "data/metadata/splits/training_split.json") == sha256(rel / "data/glacier_split_excl_clipped_surge.json"),
          groups=groups)
    check("2c_exclusion_is_test_only", all(split.get(g) == "test" for g in X), excluded=X)

    # 3 exclusion applied in every results and figure table
    bad, nglac = [], {}
    for base in [repo / RES, figures, sub]:
        for f in base.rglob("*.csv"):
            if "MANIFEST" in f.name:
                continue
            t = pd.read_csv(f, low_memory=False)
            if "excluded" in t.columns:
                t = t[t.excluded.astype(str).str.lower() == "true"]
            if "evaluated" in t.columns:
                t = t[t.evaluated.astype(str).str.lower() == "true"]
            for c in [c for c in t.columns if c.lower() in ("rgiid", "rgi_id")]:
                if t[c].astype(str).isin(X).any():
                    bad.append(str(f))
            if "n_glaciers" in t.columns:
                nglac[str(f.relative_to(base.parent))] = sorted(set(pd.to_numeric(t.n_glaciers, errors="coerce").dropna().astype(int)))
    allowed = {1422, 332, 1754}
    over = {k: v for k, v in nglac.items() if any(n > 1754 for n in v)}
    check("3_excluded_glacier_absent_from_all_tables", not bad, offending=bad)
    check("3b_no_glacier_count_above_1754", not over, offending=over, note="counts below 1,754 occur for strata (e.g. empty bands, tertiles)")
    for p in [sub / "pixel_summaries/test_residuals_long_common_xy.parquet", sub / "cache/common_xy_point_predictions.parquet"]:
        ids = pd.read_parquet(p, columns=["rgiid"]).rgiid.astype(str)
        check(f"3c_excluded_absent_{p.name}", not ids.isin(X).any() and ids.nunique() == 1754, glaciers=int(ids.nunique()))

    # 4 keys and common support
    cache = pd.read_parquet(sub / "cache/common_xy_point_predictions.parquet", columns=["method", "rgiid", "realization_index", "flat_index", "obs"])
    key = ["rgiid", "realization_index", "flat_index"]
    per_method = {m: g.set_index(key).sort_index() for m, g in cache.groupby("method")}
    idx = [v.index for v in per_method.values()]
    same_support = all(i.equals(idx[0]) for i in idx) and idx[0].is_unique
    same_obs = all(np.array_equal(per_method[m].obs.to_numpy(), per_method["constant"].obs.to_numpy()) for m in per_method)
    check("4_common_support_three_methods", same_support and same_obs and len(idx[0]) == 2540722, targets=len(idx[0]))
    common = idx[0]
    region_of = mem.set_index("rgiid").region
    common_by = {"all": pd.MultiIndex.from_arrays([common.get_level_values(i) for i in range(3)]).sort_values()}
    for r in ("whim", "ehim"):
        common_by[r] = common_by["all"][common_by["all"].get_level_values(0).map(region_of) == r]
    npz = list((paths["transfer_predictions"]).glob("*.npz")) + list(paths["coordinate_predictions"].glob("*.npz")) + \
        [rel / "predictions/test_predictions.npz"]
    key_ok = {}
    for f in npz:
        z = np.load(f, allow_pickle=False)
        k = pd.MultiIndex.from_arrays([z["rgiid"].astype(str), z["realization"], z["pixel_flat_index"]])
        ks = k[~k.get_level_values(0).isin(X)].sort_values()
        scope = "whim" if "target_whim" in f.name else "ehim" if "target_ehim" in f.name else "all"  # transfer files cover one target region
        key_ok[f.name] = bool(k.is_unique and len(ks) == len(common_by[scope]) and ks.equals(common_by[scope]))
    check("4b_prediction_keys_unique_and_equal_common_targets", all(key_ok.values()), files=key_ok)

    # 5 masks fixed, targets = void & glacier & finite reference
    inv = pd.read_csv(repo / "data/metadata/realization_inventory.csv")
    tcount = cache[cache.method == "constant"].groupby(["rgiid", "realization_index"]).size()
    mism, maskdiff, denom = 0, 0, 0
    frozen_chips = paths.root / "prepared/voids_frozen/chips"
    for g in sel.evaluated:
        c = np.load(paths["chips"] / f"{g}.npz")
        fz = np.load(frozen_chips / f"{g}.npz")
        maskdiff += int(not np.array_equal(c["void_mask"], fz["void_mask"]))
        gm = c["glacier_mask"].astype(bool)
        valid = gm & np.isfinite(c["dhdt"])
        n_valid = int(valid.sum())
        denom += int(n_valid != int(inv.loc[inv.rgiid == g, "n_valid_glacier_pixels"].iloc[0]))
        for r in range(c["void_mask"].shape[0]):
            n = int((c["void_mask"][r].astype(bool) & valid).sum())
            mism += int(n != int(tcount.get((g, r), 0)))
    check("5_void_masks_identical_to_frozen_chips", maskdiff == 0, glaciers_checked=len(sel.evaluated), differing=maskdiff)
    check("5b_targets_are_void_pixels_with_finite_reference", mism == 0, mismatched_glacier_realizations=mism)
    check("6_valid_pixel_denominators_match_inventory", denom == 0, mismatched=denom)
    con = pd.read_csv(paths["sensitivity_metrics"] / "per_glacier_error_contributions.csv")
    A = con.valid_area_km2 * 1e6
    scale = max(float(np.max(np.abs(con[f"mean_vol_{m}"] - con[f"mean_spec_{m}"] * A) / np.maximum(np.abs(con[f"mean_vol_{m}"]), 1)))
                for m in ["constant", "hypsometric", "hybrid"])
    area_pix = float(np.max(np.abs(np.rint(A / 900) - inv.drop_duplicates("rgiid").set_index("rgiid").n_valid_glacier_pixels.reindex(con.rgiid).to_numpy())))
    check("6b_integrated_equals_specific_times_valid_area", scale < 1e-9 and area_pix == 0, max_rel_diff=scale, max_pixel_diff=area_pix)

    # 7 tables
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, str(repo / "analysis/manuscript/build_tables.py"), "--evidence", str(repo / RES / "evidence"),
                        "--out", tmp], check=True, capture_output=True)
        names = ["tab_pixel.tex", "tab_paired.tex", "tab_glacier.tex", "tab_volume.tex", "tab_transfer.tex", "tab_coordinates.tex"]
        same_repo = {n: (Path(tmp) / "tables" / n).read_bytes() == (repo / RES / "tables" / n).read_bytes() for n in names}
        same_ms = {n: (Path(tmp) / "tables" / n).read_bytes() == (repo / "manuscript/main/tables" / n).read_bytes() for n in names}
    check("7_tables_rebuild_identical", all(same_repo.values()) and all(same_ms.values()),
          repo=same_repo, manuscript=same_ms)

    # 8 reported manuscript values
    p = pd.read_csv(repo / RES / "evidence/point_metrics.csv").query("excluded")
    v = lambda s, m, k, c: float(p[(p.scope == s) & (p.method == m) & (p.kind == k)][c].iloc[0])  # noqa: E731
    red = lambda base, x: 100 * (base - x) / base  # noqa: E731
    want = {}
    for s, w in zip(["whim", "ehim", "all"], [(20.1, 16.4, 13.1, 19.8, 6.03), (16.9, 14.7, 15.3, 16.1, 9.76), (19.4, 15.9, 13.5, 19.1, 6.20)]):
        got_ = (red(v(s, "hypsometric", "specific", "mae"), v(s, "xgb", "specific", "mae")), red(v(s, "hypsometric", "pixel", "mae"), v(s, "xgb", "pixel", "mae")),
                red(v(s, "hypsometric", "pixel", "nmad"), v(s, "xgb", "pixel", "nmad")), red(v(s, "hypsometric", "volume", "mae"), v(s, "xgb", "volume", "mae")),
                red(v(s, "hypsometric", "volume", "rmse"), v(s, "xgb", "volume", "rmse")))
        for lab, gv, wv in zip(["specific_mae", "pixel_mae", "pixel_nmad", "volume_mae", "volume_rmse"], got_, w):
            want[f"{s}_{lab}"] = (sig3(gv), wv)
    want["all_specific_mae_hyp"] = (sig3(v("all", "hypsometric", "specific", "mae")), 0.0639)
    want["all_specific_mae_hybrid"] = (sig3(v("all", "xgb", "specific", "mae")), 0.0515)
    t = pd.read_csv(repo / RES / "evidence/transfer_metrics.csv").set_index(["target", "source"])
    for tg, oth, wm, wr in [("whim", "ehim", 17.0, 72.5), ("ehim", "whim", 10.8, -2.58)]:
        s_, c_ = t.loc[(tg, tg)], t.loc[(tg, oth)]
        want[f"transfer_{tg}_mae"] = (sig3(100 * (c_.glacier_mae - s_.glacier_mae) / s_.glacier_mae), wm)
        want[f"transfer_{tg}_int_rmse"] = (sig3(100 * (c_.integrated_rmse - s_.integrated_rmse) / s_.integrated_rmse), wr)
    c = pd.read_csv(repo / RES / "evidence/coordinate_all_metrics.csv").query("excluded").set_index(["scope", "arm"])
    for s, w in [("whim", (1.23, 84.1, 0.0292, 120)), ("ehim", (1.48, 88.5, 0.255, 458)), ("combined", (1.29, 83.3, 0.0405, 37.9))]:
        o, n = c.loc[(s, "off")], c.loc[(s, "on_absolute")]
        got_ = (red(o.glacier_mae, n.glacier_mae), red(abs(o.glacier_bias), abs(n.glacier_bias)), red(o.integrated_rmse, n.integrated_rmse),
                -red(abs(o.integrated_bias), abs(n.integrated_bias)))
        for lab, gv, wv in zip(["mae", "abs_bias", "int_rmse", "int_abs_bias_increase"], got_, w):
            want[f"coord_{s}_{lab}"] = (sig3(gv), wv)
    comp = pd.read_csv(sub / "glacier_wide_comparison/glacier_wide_comparison_specific_exclude_all_glaciers.csv")
    wins = comp.pivot(index="rgiid", columns="method", values="mean_absolute_error")
    want["hybrid_wins_pct"] = (sig3(100 * (wins.xgb < wins.hypsometric).mean()), 69.8)
    ci = pd.read_csv(repo / RES / "evidence/coordinate_all_intervals.csv").query("excluded").set_index(["scope", "metric"])
    pattern = {"mae_above_zero": all(ci.loc[(s, "glacier_mae"), "ci_low"] > 0 for s in ["whim", "ehim", "combined"]),
               "abs_bias_W_C_above_E_spans": ci.loc[("whim", "glacier_bias"), "ci_low"] > 0 and ci.loc[("combined", "glacier_bias"), "ci_low"] > 0
               and ci.loc[("ehim", "glacier_bias"), "ci_low"] < 0 < ci.loc[("ehim", "glacier_bias"), "ci_high"],
               "integrated_span_zero": all(ci.loc[(s, m), "ci_low"] < 0 < ci.loc[(s, m), "ci_high"] for s in ["whim", "ehim", "combined"]
                                           for m in ["integrated_mae", "integrated_rmse", "integrated_bias"])}
    bad = {k: v_ for k, v_ in want.items() if v_[0] != v_[1]}
    check("8_manuscript_values_reproduced", not bad and all(pattern.values()), mismatches=bad, interval_patterns=pattern, n_values=len(want))

    # 9 manuscript text
    tex = (repo / "manuscript/main/main.tex").read_text()
    active = "\n".join(l for l in tex.splitlines() if not l.lstrip().startswith("%"))
    stale = [s for s in ["(19.3\\%)", "by 19.3\\%", "19.3\\% below hypsometric", "16.3\\%", "69.7\\%", "0.029\\%", "0.26\\%", "0.041\\%",
                         "from 0.064 to 0.052", "1,755", "71.8"] if s in active]
    present = [s for s in ["19.4\\%", "16.4\\%", "69.8\\%", "0.0292\\%", "0.255\\%", "0.0405\\%", "0.0639", "0.0515", "1,754", "2,540,722", "RGI60-14.17287"] if s not in active]
    tables = "".join((repo / "manuscript/main/tables" / n).read_text() for n in ["tab_population.tex", "tab_glacier.tex", "tab_pixel.tex"])
    tstale = [s for s in ["2,304,594", "1,423, 332 and 1,755", "1,239,146 & 1,115.23"] if s in tables]
    semis = [l for l in active.splitlines() if "RGI60-14.17287" in l and ";" in l]
    check("9_manuscript_numbers", not stale and not present and not tstale and not semis, stale=stale, missing=present, stale_tables=tstale)

    # 10 figures
    fs = json.loads((figures / "FIGURE_SOURCES.json").read_text())
    badf = [k for k, r in fs.items() if sha256(figures / k) != r["sha256"]]
    check("10_figure_hashes", not badf and len(fs) == 26, mismatched=badf, files=len(fs))

    R["all_pass"] = all(r["passed"] for r in R.values() if isinstance(r, dict))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(R, indent=1, default=str) + "\n")
    print("ALL CHECKS PASS" if R["all_pass"] else "SOME CHECKS FAILED")
    sys.exit(0 if R["all_pass"] else 1)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Run a manuscript workflow stage against an explicit data archive."""
from pathlib import Path
import argparse
import os
import shlex
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SCRIPTS = {
    'cube-grid': '01_datacube/01_define_grid.py',
    'cube-align': '01_datacube/02_align_rasters.py',
    'cube-terrain': '01_datacube/03_compute_terrain.py',
    'cube-glaciers': '01_datacube/04_rasterize_glaciers.py',
    'cube': '01_datacube/05_build_datacube.py',
    'cube-validate': '01_datacube/06_validate_datacube.py',
    'remap-chips': '02_voids/01a_remap_frozen_chips.py',
    'metadata': '02_voids/02_build_metadata.py',
    'validate-inputs': '02_voids/03_validate_inputs.py',
    'constant': '03_baselines/01_constant_local_mean.py',
    'hypsometric': '03_baselines/02_hypsometric_local_mean.py',
    'prepare': '04_model/01_prepare_rows.py',
    'cache': '05_results/01_build_prediction_cache.py',
    'pixel-stats': '05_results/02_pixel_summary_stats.py',
    'glacier-stats': '05_results/03_glacier_wide_metrics.py',
    'comparison': '05_results/04_glacier_wide_comparison.py',
    'bootstrap': '05_results/05_spatial_block_bootstrap.py',
    'figure1': '06_figures/01_fig1_study_area_map.py',
    'figure4': '06_figures/04_fig4_spatial_bootstrap.py',
}
FIGURES = {'figure2': 'fig02_distributions.py', 'figure3': 'fig03_residuals.py', 'figure5': 'fig05_glacier_wide.py'}
GROUPS = {'datacube': ['cube-grid', 'cube-align', 'cube-terrain', 'cube-glaciers', 'cube', 'cube-validate'],
          'voids': ['remap-chips', 'metadata', 'validate-inputs'], 'baselines': ['constant', 'hypsometric'],
          'results': ['cache', 'pixel-stats', 'glacier-stats', 'comparison', 'bootstrap']}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True, help='Extracted data_archive directory')
    parser.add_argument('--config', type=Path, default=HERE.parent / 'config/workflow.json')
    parser.add_argument('--datacube-config', type=Path)
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('command', choices=[*SCRIPTS, *FIGURES, *GROUPS, 'steps', 'status'])
    args, extra = parser.parse_known_args()
    extra = extra[1:] if extra and extra[0] == '--' else extra
    root = args.root.expanduser().resolve()
    if not root.is_dir(): parser.error(f'Data archive does not exist: {root}')
    os.environ['VOID_FILL_PROJECT_ROOT'] = str(root)
    os.environ['VOID_FILL_WORKFLOW_CONFIG'] = str(args.config.resolve())
    if args.datacube_config: os.environ['VOID_FILL_DATACUBE_CONFIG'] = str(args.datacube_config.resolve())
    from workflow_support import settings, workflow_path
    if args.command == 'steps':
        for name in [*SCRIPTS, *FIGURES]: print(name)
        return
    if args.command == 'status':
        for key in settings()['paths']:
            path = workflow_path(key)
            print(f"{key}: {path} ({'present' if path.exists() else 'generated by workflow'})")
        return
    stages = GROUPS.get(args.command, [args.command])
    if extra and len(stages) > 1: parser.error('Stage options require a single-stage command')
    for stage in stages:
        script = (HERE.parent / 'analysis/manuscript/figures' / FIGURES[stage]
                  if stage in FIGURES else HERE / 'src/void_fill' / SCRIPTS[stage])
        command = [sys.executable, '-B', str(script)]
        if stage == 'figure2':
            command += ['--chip-dir', str(workflow_path('chips')), '--output-base', str(workflow_path('figures') / 'fig02_distributions')]
        if stage == 'figure3':
            command += ['--input', str(workflow_path('pixel_summaries') / 'test_residuals_long_common_xy.parquet'), '--output-base', str(workflow_path('figures') / 'fig03_pixel_residuals')]
        if stage == 'bootstrap':
            config = settings()['bootstrap']
            command += ['--block-sizes-km', *map(str, config['block_sizes_km']),
                        '--primary-block-size-km', str(config['primary_block_size_km']),
                        '--n-bootstrap', str(config['n_bootstrap']), '--seed', str(config['seed'])]
        if len(stages) == 1: command += extra
        print(shlex.join(command), flush=True)
        if not args.dry_run: subprocess.run(command, check=True, cwd=root)

if __name__ == '__main__': main()
